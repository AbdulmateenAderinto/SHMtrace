INTRO = [
    "Somatic hypermutation (SHM) diversifies immunoglobulin (Ig) genes in germinal-center B cells. It is "
    "initiated by activation-induced cytidine deaminase (AID), which deaminates cytosines in Ig DNA. The "
    "resulting uracils are then copied by replication or processed by uracil excision and mismatch repair, "
    "which together produce substitutions at both G:C and A:T base pairs[@muramatsu2000,@dinoia2007,@methot2017]. "
    "Because each repair pathway leaves its own footprint, the rate, position, and spectrum of mutations are the "
    "standard readouts in studies of AID, its cofactors, and the repair pathways that act on its "
    "lesions[@dinoia2002,@rada2004,@rada2002,@zeng2001]. In mice, the most widely used reporter is the intron "
    "downstream of J_{H}4, a non-coding region that mutates like a V gene but is not subject to antigen "
    "selection[@jolly1997,@lebecque1990].",
    "The standard assay has changed little in decades. Amplicons are cloned into bacteria and sequenced colony "
    "by colony, which takes days of hands-on work and yields tens of sequences per animal[@sible2021]. "
    "High-throughput alternatives exist, but short reads fragment the amplicon and lose the linkage between "
    "mutations on the same molecule[@martin2023]. Long reads from Oxford Nanopore Technologies (ONT) now reach "
    "modal accuracies above 99% with R10.4.1 flow cells[@zhang2023,@sereika2022,@sanderson2024] and have been "
    "used to sequence Ig genes where consensus sequencing can absorb errors[@minervini2021,@subassatish2022]. "
    "Calling rare substitutions from single reads across a polyclonal population is harder. A wild-type J_{H}4 "
    "intron carries roughly one mutation per 100 bases, whereas the residual error of a single filtered read is "
    "within one or two orders of magnitude of that rate and is concentrated at particular positions and "
    "sequence contexts[@delahaye2021].",
    "Two common analysis practices make this problem worse. First, general-purpose low-frequency variant callers "
    "judge each base by its own quality score[@wilm2012], and the simple rules used in commercial software test "
    "candidates one at a time without correcting for the number of tests[@kearse2012]. Neither approach accounts "
    "for the errors that a particular library makes, so sequencing errors that recur at one position, whether "
    "from PCR, homopolymers, or a co-amplified paralog, are wrongly counted as SHM mutations. Second, reads from one animal are often "
    "pooled and treated as independent replicates, which overstates certainty because reads from the same "
    "animal share clones and PCR history[@lazic2010]. SHM studies already include the control that addresses "
    "both problems: libraries from AID-null animals or cells, prepared and sequenced alongside the samples. "
    "Existing SHM software summarizes mutations once they have been called[@maccarthy2009,@gupta2015,@yaari2013] "
    "but does not use these controls to decide which differences are mutations.",
    "Here, we describe SHMtrace, which calibrates each call against matched AID-null libraries from the "
    "same sequencing run, compares groups with the animal as the unit, and runs the complete workflow from "
    "delivered reads or Sanger chromatograms to group statistics. We validated SHMtrace with planted mutations, "
    "simulated B cell lineages, six loci from five laboratories, three sequencing platforms, and Sanger "
    "sequencing of the same mice, and we compared it with LoFreq[@wilm2012], with the long-read somatic callers "
    "ClairS[@zheng2026] and DeepSomatic[@park2026] and germline callers Clair3[@zheng2022] and "
    "DeepVariant[@poplin2018], and with the uncorrected test used in Geneious[@kearse2012].",
]

