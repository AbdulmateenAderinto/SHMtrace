LIMITATIONS = (
    "This study has limitations that temper its conclusions. SHMtrace requires AID-null control libraries "
    "from the same sequencing run, because errors and basecallers change between runs; a background measured in "
    "a different run can rank samples but cannot calibrate them. Its calls are filtered apparent variants. "
    "Without UMIs, early PCR errors, PCR recombination, and duplicates cannot be distinguished from true "
    "mutations or from expanded clones, and mutation trees are therefore read-level reconstructions. Mutations "
    "carried by a single read are recovered in aggregate rather than individually, and unique-variant density "
    "depends on depth, so libraries must be compared at matched depth. Because the FDR is estimated from the "
    "controls themselves, a control library noisier than its peers, such as the unused library of N114 subclone "
    "C3, allows the FDR to exceed the nominal level, and a control that is far noisier than the others can be "
    "set aside only when there are three or more controls to compare. An artifact present in one library but "
    "absent from the controls is not removed by calibration; the spectrum, clustering, and targeting checks "
    "flag such cases, but they require a person to judge them. At a weak AID target such as *Pim1*, the signal "
    "approaches the background at the depths tested. Our validation used three animals per group, one nanopore "
    "run per assay, and one locus per cell system. The thresholds were chosen on our libraries and applied to "
    "the public datasets without retuning, but a held-out sequencing run of new animals would test them "
    "further. Indels were validated on planted events in nanopore reads and on one Illumina dataset but not yet on "
    "nanopore reads of a library with a known indel phenotype, and UMI consensus was validated on rRNA "
    "operons rather than an SHM library. Where UMIs or duplex reads are available, molecule-level consensus is "
    "preferable to calibrating single reads, and SHMtrace supports both approaches.")

